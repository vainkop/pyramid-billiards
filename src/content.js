/** Beyond this tip offset (as a fraction of the safe radius) a miscue becomes likely. */
export const MISCUE_LIMIT = 0.95;

/** Name and effect of the shot for a tip position and cue elevation. */
export function technique(ox, oy, elev = 0) {
  const side = ox > 0.25 ? 'правый винт' : ox < -0.25 ? 'левый винт' : null;
  const dir = ox > 0 ? 'вправо' : 'влево';
  let result;
  if (elev >= 0.55) {
    result = side
      ? { name: 'Массе', desc: `Биток пойдёт по крутой дуге ${dir}` }
      : { name: 'Кий с наклоном', desc: 'Сдвинь точку в сторону — биток пойдёт по дуге' };
  } else if (elev >= 0.25 && side) {
    result = { name: 'Полумассе', desc: `Биток пойдёт по пологой дуге ${dir}` };
  } else {
    let name;
    let desc;
    // a little below centre is still a stop shot: that is how it is played from a distance
    if (oy > 0.55) [name, desc] = ['Сильный накат', 'Биток уверенно покатится вслед за шаром'];
    else if (oy > 0.2) [name, desc] = ['Накат', 'Биток покатится вперёд за прицельным шаром'];
    else if (oy < -0.7) [name, desc] = ['Сильная оттяжка', 'Биток резко откатится назад'];
    else if (oy < -0.5) [name, desc] = ['Оттяжка', 'Биток откатится назад после удара'];
    else [name, desc] = ['Клапштос', 'При прямом ударе биток остановится на месте шара'];
    if (!side) result = { name, desc };
    else if (name === 'Клапштос') result = { name: 'Боковой винт', desc: `Отскок от борта уйдёт ${dir}` };
    else result = { name: `${name} + винт`, desc: `${desc}, от борта — ${dir}` };
  }
  if (Math.hypot(ox, oy) > MISCUE_LIMIT) result.desc = 'Риск кикса! Слишком далеко от центра';
  return result;
}
